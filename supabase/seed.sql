-- Time slots per day: 6 teaching periods + recess (period 4)
-- ---------------------------------------------------------------------
insert into public.time_slots (working_day_id, period_number, start_time, end_time, is_break) 
select wd.id, p.period::int, p.start::time, p.stop::time, p.break_flag
from (
  values
    (1,'09:45','10:45',false),
    (2,'10:45','11:45',false),
    (3,'11:45','12:45',false),
    (4,'12:45','13:30',true),
    (5,'13:30','14:30',false),
    (6,'14:30','15:30',false),
    (7,'15:30','16:25',false)
) as p(period, start, stop, break_flag)
cross join public.working_days wd
on conflict (working_day_id, period_number) do nothing;

